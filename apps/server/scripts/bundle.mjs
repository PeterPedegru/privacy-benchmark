// Bundles the server for production (SEC-19, EFF-32): `node dist/index.js` instead of tsx under pnpm.
//
// - src/index.ts and the @pb/* workspace packages (TypeScript source) are bundled into dist/server.js.
// - Every npm dependency stays external and is resolved from apps/server/node_modules at runtime, which keeps
//   native modules (better-sqlite3, @resvg/resvg-js) and file lookups (fonts, the Anthropic SDK) working unchanged.
// - dist/ sits at the same depth as src/, so SERVER_ROOT/REPO_ROOT (env.ts), the drizzle migrations folder and
//   the card fonts resolve exactly as they do from source.
// - dist/index.js is a tiny launcher that sets process defaults (UV_THREADPOOL_SIZE) before any module loads.
// - dist/extract-worker.js (HTML extraction worker) and dist/pdf-child.js (PDF extraction process) are their own
//   entries; the server starts them by path next to dist/server.js.
//
// BUNDLE_OUTDIR=<name> builds into apps/server/<name> instead of dist/ (the bundle test uses a private directory so
// it never deletes the dist/ that e2e or a running server uses). It must sit directly under apps/server, like dist/.
import { readFileSync, rmSync, writeFileSync } from "node:fs";
import { builtinModules } from "node:module";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outdir = resolve(root, process.env.BUNDLE_OUTDIR || "dist");
if (dirname(outdir) !== root) throw new Error(`BUNDLE_OUTDIR must be a directory directly under ${root} (paths resolve relative to src/'s depth)`);
const out = (file) => relative(root, join(outdir, file));
const pkg = JSON.parse(readFileSync(resolve(root, "package.json"), "utf8"));
const runtimeDeps = new Set(Object.keys(pkg.dependencies ?? {}));
const builtins = new Set(builtinModules);

const packageName = (spec) => (spec.startsWith("@") ? spec.split("/").slice(0, 2).join("/") : spec.split("/")[0]);

/** Bundle @pb/*, externalize the rest, and fail if an external isn't a runtime dependency of the server. */
const externals = {
  name: "externals",
  setup(b) {
    const missing = new Set();
    b.onResolve({ filter: /^[^./]/ }, (args) => {
      if (args.path.startsWith("@pb/")) return undefined;
      if (args.path.startsWith("node:") || builtins.has(packageName(args.path))) return { path: args.path, external: true };
      const name = packageName(args.path);
      if (!runtimeDeps.has(name)) missing.add(`${name} (imported from ${relative(root, args.importer)})`);
      return { path: args.path, external: true };
    });
    b.onEnd((result) => {
      if (missing.size)
        result.errors.push({
          text: `Not in apps/server dependencies, so it won't resolve at runtime: ${[...missing].join(", ")}`,
        });
    });
  },
};

rmSync(outdir, { recursive: true, force: true });
const started = Date.now();
const result = await build({
  absWorkingDir: root,
  entryPoints: ["src/index.ts"],
  outfile: out("server.js"),
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  tsconfig: "tsconfig.json",
  jsx: "automatic",
  jsxImportSource: "react",
  sourcemap: "linked",
  sourcesContent: false,
  legalComments: "none",
  logLevel: "warning",
  metafile: true,
  plugins: [externals],
});

// HTML extraction runs in worker threads (SEC-3) and PDFs in a child process (R3-SEC-1); each is its own entry so
// the pool can start it.
for (const [entry, file] of [
  ["src/lib/extract-worker.ts", "extract-worker.js"],
  ["src/lib/pdf-child.ts", "pdf-child.js"],
]) {
  await build({
    absWorkingDir: root,
    entryPoints: [entry],
    outfile: out(file),
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node22",
    tsconfig: "tsconfig.json",
    sourcemap: "linked",
    sourcesContent: false,
    legalComments: "none",
    logLevel: "warning",
    plugins: [externals],
  });
}

writeFileSync(
  resolve(outdir, "index.js"),
  `// Generated by scripts/bundle.mjs. Sets process defaults before any module (or the thread pool) loads.
process.env.UV_THREADPOOL_SIZE ||= "16";
await import("./server.js");
`,
);

const bytes = result.metafile.outputs[out("server.js")]?.bytes ?? 0;
console.log(`[bundle] ${out("server.js")} ${(bytes / 1024).toFixed(0)} KB in ${Date.now() - started} ms`);
